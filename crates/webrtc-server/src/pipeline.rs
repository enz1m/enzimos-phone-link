//! GStreamer WebRTC pipeline for server-side media encoding and streaming.
//!
//! Creates a single `webrtcbin` element that acts as the server peer.
//! The pipeline captures from PipeWire (or a test source), encodes to H.264,
//! and sends via WebRTC with an SCTP data channel for input control.

