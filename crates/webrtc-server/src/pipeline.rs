/// Callback for IPC messages generated by the pipeline (offers, ICE, etc.).
pub type IpcSender = Box<dyn Fn(FromWebRtc) + Send + Sync>;

/// Worker transports; desktop-window leases require the Wayland capability helper.
pub enum InputHandler {
    /// EIS input bridge (full multi-touch, scoped).
    Eis(InputBridge),
    /// Uses a display-scoped virtual-input worker or a leased-seat helper.
    Wayland(WaylandInputBridge),
}

impl InputHandler {
    /// Forward a control message to the input system.
    pub fn send(&self, message: &enzremote_control::ControlMessage) -> Result<(), String> {
        match self {
            InputHandler::Eis(bridge) => bridge.send(message),
            InputHandler::Wayland(bridge) => bridge.send(message),
        }
    }

    /// Start the input handler (spawns the worker process).
    pub fn start(&self) -> Result<(), String> {
        match self {
            InputHandler::Eis(bridge) => bridge.start(),
            InputHandler::Wayland(bridge) => bridge.start(),
        }
    }

    /// Stop the input handler.
    pub fn stop(&self) {
        match self {
            InputHandler::Eis(bridge) => bridge.stop(),
            InputHandler::Wayland(bridge) => bridge.stop(),
        }
    }
}

