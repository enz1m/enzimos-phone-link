#![forbid(unsafe_code)]
//! Shared IPC protocol types for communication between the enzremote
//! signaling server and per-session WebRTC pipeline processes.
//!
//! Messages are line-delimited JSON over a Unix stream socket.
//! The signaling server connects to the WebRTC server's IPC socket and
//! relays SDP/ICE messages bidirectionally.

use serde::{Deserialize, Serialize};

/// Messages from the signaling server to the WebRTC pipeline.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum ToWebRtc {
    /// Client's SDP answer in response to our offer.
    Answer { sdp: String },
    /// Client's ICE candidate.
    Ice {
        candidate: String,
        sdp_m_line_index: u32,
    },
    /// Graceful shutdown request.
    Shutdown,
}

/// Messages from the WebRTC pipeline to the signaling server.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum FromWebRtc {
    /// SDP offer generated by the pipeline.
    Offer { sdp: String },
    /// ICE candidate generated by the pipeline.
    Ice {
        candidate: String,
        sdp_m_line_index: u32,
    },
    /// WebRTC connection established, media flowing.
    Connected,
    /// ICE connection entered Disconnected state (peer may return).
    /// A timeout will escalate to `Error` if the peer does not reconnect.
    Disconnected,
    /// Pipeline error.
    Error { reason: String },
    /// Pipeline ready, IPC socket bound and listening.
    Ready,
}

/// Maximum IPC message size (256 KiB).
pub const MAX_IPC_MESSAGE_SIZE: usize = 262_144;

/// Parse a `ToWebRtc` message from a JSON line.
pub fn parse_to_webrtc(line: &str) -> Result<ToWebRtc, String> {
    if line.len() > MAX_IPC_MESSAGE_SIZE {
        return Err("IPC message exceeds maximum size".into());
    }
    serde_json::from_str(line).map_err(|e| format!("invalid IPC message: {e}"))
}

/// Parse a `FromWebRtc` message from a JSON line.
pub fn parse_from_webrtc(line: &str) -> Result<FromWebRtc, String> {
    if line.len() > MAX_IPC_MESSAGE_SIZE {
        return Err("IPC message exceeds maximum size".into());
    }
    serde_json::from_str(line).map_err(|e| format!("invalid IPC message: {e}"))
}

/// Serialize a message to a JSON line (no trailing newline).
pub fn serialize_message<T: Serialize>(message: &T) -> Result<String, String> {
    serde_json::to_string(message).map_err(|e| format!("failed to serialize IPC message: {e}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_oversized_message() {
        let huge = "a".repeat(MAX_IPC_MESSAGE_SIZE + 1);
        assert!(parse_to_webrtc(&huge).is_err());
        assert!(parse_from_webrtc(&huge).is_err());
    }
}

